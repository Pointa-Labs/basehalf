import { basename, dirname } from '../../../../base/common/resources.js';
import { URI } from '../../../../base/common/uri.js';
import { localize } from '../../../../nls.js';
import { baseHalfCanvasGenerationCardSize } from '../../canvas/common/basehalfCanvasModel.js';
import {
	baseHalfGenerationInfoOfMade,
	baseHalfGenerationNameOrdinal,
	baseHalfGenerationNameParts
} from '../common/basehalfGenerationInfo.js';
import { baseHalfModelFileExtension, baseHalfVideoChoiceRatio, findBaseHalfVideoModel, IBaseHalfVideoCatalog } from '../common/basehalfVideoCatalog.js';
import { IBaseHalfGenerationCardSnapshot, IBaseHalfGenerationCardStore } from '../common/basehalfVideoGeneration.js';
import { baseHalfParentCanvasFolder, IBaseHalfPlacementServices, placeBaseHalfCardsBeside } from './basehalfGenerationPlacement.js';

/** How often a new name is chosen when another one took the name meanwhile. */
const NAME_ATTEMPTS = 3;

/** What making a new version of a generated file needs. */
export interface IBaseHalfNewVersionServices extends IBaseHalfPlacementServices {
	readonly cardStore: IBaseHalfGenerationCardStore;
}

/**
 * New Version (generation cards, "New Version"): a new draft beside a card
 * with its file, in the same folder and named like it with the next free
 * number, holding the prompt, provider, model, mode, and values of the card's
 * `made.yaml` without the seed, and the card's inputs in their order. Its
 * card is placed to the right of the original. It generates nothing. Rejects
 * for a card without its file or whose record cannot be read; the caller
 * makes it one step of undo.
 */
export async function createBaseHalfNewVersion(
	services: IBaseHalfNewVersionServices,
	snapshot: IBaseHalfGenerationCardSnapshot,
	workspaceFolder: URI,
	catalog: IBaseHalfVideoCatalog | undefined
): Promise<URI> {
	const name = basename(snapshot.resource);
	if (!snapshot.hasFile) {
		throw new Error(localize('basehalf.generation.newVersion.noFile', "{0} has no file yet: it is a draft, and its own panel makes it.", name));
	}
	if (!snapshot.made) {
		throw new Error(snapshot.madeUnreadable
			? localize('basehalf.generation.newVersion.noRecord', "BaseHalf could not read what made {0}, so it cannot make a new version of it.", name)
			: localize('basehalf.generation.newVersion.notGenerated', "{0} was not generated by BaseHalf, so there is nothing to make a new version from.", name));
	}
	const info = baseHalfGenerationInfoOfMade(snapshot.made);
	const parent = dirname(snapshot.resource);
	const parts = baseHalfGenerationNameParts(name);
	const ref = findBaseHalfVideoModel(catalog, info.provider, info.model);
	// An image model delivers its own format; the new draft takes its extension, as a new draft of that model does.
	const extension = ref && ref.model.kind === 'image' && snapshot.kind === 'image' ? baseHalfModelFileExtension(ref.model) : parts.extension;
	let draft: URI | undefined;
	for (let attempt = 1; !draft; attempt++) {
		const next = await services.cardStore.nextFreeName(parent, parts.base, extension, baseHalfGenerationNameOrdinal(name));
		try {
			draft = await services.cardStore.createDraft(parent, next, info, snapshot.upstream);
		} catch (error) {
			// Another one took the name meanwhile: the next free one.
			if (attempt >= NAME_ATTEMPTS || await services.cardStore.nextFreeName(parent, parts.base, extension, baseHalfGenerationNameOrdinal(name)) === next) {
				throw error;
			}
		}
	}
	const slash = snapshot.path.lastIndexOf('/');
	const draftPath = slash < 0 ? basename(draft) : `${snapshot.path.slice(0, slash)}/${basename(draft)}`;
	await placeBaseHalfCardsBeside(services, baseHalfParentCanvasFolder({ resource: snapshot.resource, workspaceFolder, relativePath: snapshot.path }), snapshot.path, [{
		path: draftPath,
		size: baseHalfCanvasGenerationCardSize(snapshot.kind, baseHalfVideoChoiceRatio(catalog, info))
	}]);
	return draft;
}
